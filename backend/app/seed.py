"""Database seeding.

`ensure_catalogue` is idempotent and runs on every startup so the exercise
catalogue always matches app/catalogue.py.

`seed_demo` builds the demo clinic used for walkthroughs. Historical sessions
are generated by simulating plausible per-repetition angle measurements and
then running them through the *real* movement-quality layer, so every number
on the dashboard comes from the same code path a live session uses.
"""

