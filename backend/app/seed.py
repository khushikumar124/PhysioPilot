def ensure_catalogue(db: Session) -> None:
    """Insert or update catalogue exercises. Safe to call repeatedly."""
    by_slug = {e.slug: e for e in db.scalars(select(Exercise))}
    for spec in EXERCISES:
        exercise = by_slug.get(spec["slug"])
        if exercise is None:
            db.add(Exercise(**spec))
        else:
            for key, value in spec.items():
                setattr(exercise, key, value)
    db.commit()


def _make_user(db: Session, name: str, email: str, role: UserRole) -> User:
    user = User(
        name=name,
        email=email,
        password_hash=hash_password(DEMO_PASSWORD),
        role=role,
    )
    db.add(user)
    db.flush()
    return user


def _simulate_reps(
    count: int, peak: float, consistency: float, rng: random.Random
) -> list[quality.RepFeatures]:
    """Plausible per-repetition measurements around a target peak angle."""
    reps = []
    for i in range(count):
        jitter = rng.gauss(0, (1 - consistency) * 9)
        max_angle = max(10.0, min(150.0, peak + jitter))
        min_angle = max(0.0, rng.gauss(6, 3))
        duration = max(0.6, rng.gauss(3.2, 0.9 * (1.4 - consistency)))
        reps.append(
            quality.RepFeatures(
                index=i,
                min_angle=round(min_angle, 1),
                max_angle=round(max_angle, 1),
                duration_seconds=round(duration, 2),
                peak_velocity=round(abs(rng.gauss(45, 10)), 1),
                mean_visibility=round(min(1.0, max(0.3, rng.gauss(0.88, 0.07))), 2),
            )
        )
    return reps


def _record_session(
    db: Session,
    patient: PatientProfile,
    pe: PrescribedExercise,
    when: datetime,
    reps_attempted: int,
    peak: float,
    consistency: float,
    rng: random.Random,
) -> None:
    target = pe.target_rom or pe.exercise.default_target_rom
    tracked = pe.exercise.cv_supported
    features = _simulate_reps(reps_attempted, peak, consistency, rng) if tracked else []
    assessment = quality.assess_session(features, target)

    session = ExerciseSession(
        patient_id=patient.id,
        prescribed_exercise_id=pe.id,
        started_at=when - timedelta(minutes=4),
        completed_at=when,
        status=SessionStatus.completed,
        reps_prescribed=pe.repetitions,
        reps_attempted=reps_attempted,
        tracking_mode="camera" if tracked else "self_reported",
        pose_coverage=round(rng.uniform(0.86, 0.99), 2) if tracked else None,
    )
    if tracked:
        session.reps_valid = assessment.reps_valid
        session.quality_score = assessment.quality_score
        session.rom_max = assessment.rom_max
        session.rom_mean = assessment.rom_mean
    session.feedback = " ".join(
        quality.patient_feedback(assessment, reps_attempted, pe.repetitions)
    )
    db.add(session)
    db.flush()

    for feature, verdict in zip(features, assessment.assessments):
        db.add(
            SessionRep(
                session_id=session.id,
                index=feature.index,
                min_angle=feature.min_angle,
                max_angle=feature.max_angle,
                rom=round(feature.excursion, 1),
                duration_seconds=feature.duration_seconds,
                peak_velocity=feature.peak_velocity,
                mean_visibility=feature.mean_visibility,
                valid=verdict.valid,
                classification=verdict.classification,
                reason=verdict.reason,
            )
        )

    if session.rom_max is not None:
        db.add(
            ProgressMetric(
                patient_id=patient.id,
                exercise_id=pe.exercise_id,
                session_id=session.id,
                metric_type="rom_max",
                value=session.rom_max,
                recorded_at=when,
            )
        )


def _build_plan(
    db: Session,
    patient: PatientProfile,
    therapist: PhysiotherapistProfile,
    title: str,
    condition: str,
    start_offset_days: int,
    items: list[dict],
    catalogue: dict[str, Exercise],
) -> RehabilitationPlan:
    today = datetime.now(timezone.utc).date()
    plan = RehabilitationPlan(
        patient_id=patient.id,
        therapist_id=therapist.id,
        title=title,
        condition=condition,
        start_date=today - timedelta(days=start_offset_days),
        end_date=today + timedelta(days=28 - start_offset_days),
        status=PlanStatus.active,
    )
    db.add(plan)
    db.flush()
    for order, item in enumerate(items):
        db.add(
            PrescribedExercise(
                plan_id=plan.id,
                exercise_id=catalogue[item["slug"]].id,
                sets=item["sets"],
                repetitions=item["reps"],
                frequency_per_day=item.get("frequency", 1),
                instructions=item.get("instructions", ""),
                target_rom=item.get("target_rom"),
                order_index=order,
            )
        )
    db.flush()
    db.refresh(plan)
    return plan


